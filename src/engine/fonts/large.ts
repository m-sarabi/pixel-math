export const largeFont: BitmapFont = {
  name: 'Large (9×12)',
  metrics: largeMetrics,
  getGlyph(key: string): GlyphData | undefined {
    return largeGlyphs[key] || standardFont.getGlyph(key);
  },
  hasGlyph(key: string): boolean {
    return key in largeGlyphs || standardFont.hasGlyph(key);
  },
};

export const subLargeFont: BitmapFont = compactFont;
